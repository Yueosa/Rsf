// 0x00 —— 变量、类型与打印
//
// 运行: cargo run --bin 0x00_arith
//
// ── 题目 ────────────────────────────────────────────────────────
//
// 小A 有 17 块钱, 小B 有 5 块钱. 请把这些数字存进变量, 然后打印:
//
//   1. 两人一共多少钱
//   2. 小A 比小B 多多少钱
//   3. 两人钱数相乘
//   4. 小A 的钱能买几个 5 块钱的东西, 还剩多少  (= 整除 + 余数)
//   5. 平均每人多少钱, 保留两位小数
//
// 期望输出 (措辞随意, 数字必须对):
//
//   合计: 22
//   差额: 12
//   乘积: 85
//   整除: 3, 余数: 2
//   平均: 11.00
//
// ── 要求 ────────────────────────────────────────────────────────
//
// * 17 和 5 只许出现一次, 存进变量, 后面都用变量算
// * 第 5 题必须真算出小数, 不许写死 "11.00", 也不许用 if 特判
// * 加分: 五行的数字右对齐成一列
//
// ── 提示 ────────────────────────────────────────────────────────
//
// * 整数相除会截断小数: 17 / 5 得到 3
// * 想要小数结果, 至少一边要是浮点: 17 as f64 / 5.0
// * 保留两位小数: {:.2}   右对齐占 3 格: {:>3}

fn main() {
    let am: i32 = 17;
    let bm: i32 = 5;

    println!("合计:\t {}", sum(am, bm));
    println!("差额:\t {}", sub(am, bm));
    println!("乘积:\t {}", mul(am, bm));
    println!("整除:\t {}, 余数:\t {}", div(am, bm), rem(am, bm));
    println!("平均:\t {:.2}", avg(am, bm));
}

fn sum(a: i32, b: i32) -> i32 {
    a + b
}

fn sub(a: i32, b: i32) -> i32 {
    a - b
}

fn mul(a: i32, b: i32) -> i32 {
    a * b
}

fn div(a: i32, b: i32) -> i32 {
    a / b
}

fn rem(a: i32, b: i32) -> i32 {
    a % b
}

fn avg(a: i32, b: i32) -> f32 {
    sum(a, b) as f32 / 2.0
}

